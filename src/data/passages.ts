// Longer pieces to read along with: public-domain poems and tales, plus original dialogues.
// Stress marks on every word of more than one syllable. An empty line is a stanza break.

export type PassageGroup = 'poems' | 'tales' | 'dialogues' | 'mine';

export type Passage = {
  id: string;
  group: PassageGroup;
  title: string;
  titleEn: string;
  author?: string;
  lines: string[];
};

